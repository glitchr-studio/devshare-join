<h1>DevShare support</h1>

<p>DevShare shares the websites, React Native apps and services a developer runs on their Mac with guests anywhere, for as long as they choose. The Mac app shares in its Developer view and joins in its Simple view; the iPhone and iPad app joins.</p>

<h2>Getting help</h2>
<p>Write to <a href="mailto:support@glitchr.io">support@glitchr.io</a>. Say which app (Mac, or iPhone and iPad), its version, and what you saw. Answers come from France, on working days.</p>

<h2>Common questions</h2>

<p><strong>The app says “no connection”.</strong> The device has neither Wi‑Fi nor mobile data. Connect it; the host's Mac can be on any network.</p>

<p><strong>“The session is over”.</strong> Sessions last the time the host chose, and end on their own. If the host starts it again under the same invitation, “Join again” takes you back in without scanning.</p>

<p><strong>I have a code but no QR code or link.</strong> A code typed by hand needs a join server, set in the app's Settings. Without one, scan the QR code the host's Mac shows, or open the link they send.</p>

<p><strong>A page will not open.</strong> Only the projects in the session are reachable, and only while it lasts. Ask the host whether the project is running and part of the session.</p>

<p><strong>A site asks for a name and a password.</strong> The host's site is protected: ask them for it. DevShare asks once, and remembers it until the session ends.</p>

<p><strong>I do not see my projects on the Mac.</strong> Switch to Developer, at the top right of the window.</p>

<p><strong>Where do comments and recordings go?</strong> To the host's Mac, in the session's timeline, next to the page they are about.</p>

<p><strong>Can my guests reach me when I am not on their network?</strong> Yes. When no direct path exists the connection goes through a relay, by default one of the public relays of <a href="https://www.iroh.computer">n0 (number 0)</a>, or one you run yourself: see <a href="https://github.com/glitchr-studio/devshare-relay">devshare-relay</a>.</p>

